-- 014: мультипроектность — у организатора несколько мероприятий.
-- Строка event_settings = один проект: своё оформление, тексты, папка
-- с фотографиями и метаданные (дата, описание, архив).
-- Старые записи без meta получают значения по умолчанию.

alter table event_settings
  add column if not exists meta jsonb not null default '{}'::jsonb;
