// Колонки ленты: направление, скорость и стартовое смещение у каждой
// свои, чтобы поток выглядел живым, а не синхронным.
const COLUMNS = [
  { dir: "up", duration: 95, delay: -18 },
  { dir: "down", duration: 120, delay: -55 },
  { dir: "up", duration: 130, delay: -70 },
  { dir: "down", duration: 105, delay: -30 },
  { dir: "up", duration: 115, delay: -85 },
  { dir: "down", duration: 100, delay: -45 },
] as const;

function MessageBubble({ message, index }: { message: Message; index: number }) {
  const avatar = AVATAR_GRADIENTS[index % AVATAR_GRADIENTS.length];
  const body = (
    <div
      className={`max-w-[230px] px-3.5 py-2 text-[12.5px] leading-snug text-white ${
        message.out
          ? "rounded-[18px] rounded-br-[6px] bg-[#0a84ff]"
          : "rounded-[18px] rounded-bl-[6px] bg-[color-mix(in_srgb,var(--el-text)_16%,transparent)]"
      }`}
    >
      {message.text}
    </div>
  );

  return (
    <div className={`flex items-end gap-2 ${message.out ? "flex-row-reverse" : ""}`}>
      {!message.out && (
        <div
          className="h-6 w-6 shrink-0 rounded-full"
          style={{ background: avatar }}
          aria-hidden
        />
      )}
      <div className="min-w-0">
        {!message.out && (
          <p className="mb-0.5 px-1 text-[9.5px] font-medium text-[var(--el-text-dim)]">
            {message.name}
          </p>
        )}
        {body}
      </div>
    </div>
  );
}

